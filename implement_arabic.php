// Function to translate a string to Arabic
function translateToArabic($text, $dictionary) {
    // Check if exact match exists in dictionary
    if (isset($dictionary[$text])) {
        return $dictionary[$text];
    }
    
    // Check for partial matches (contains)
    foreach ($dictionary as $english => $arabic) {
        if (stripos($text, $english) !== false) {
            return str_ireplace($english, $arabic, $text);
        }
    }
    
    // If no match found, return original (will need manual review)
    return $text;
}

