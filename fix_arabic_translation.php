$untranslatedCount = 0;

foreach ($enTranslations as $key => $value) {
    if (is_string($value) && !empty($value)) {
        $translated = translateToArabic($value, $arabicTranslations);
        $arabicJson[$key] = $translated;
        
        if ($translated !== $value) {
            $translatedCount++;
        } else {
            $untranslatedCount++;
        }
    } else {
        $arabicJson[$key] = $value;
    }
}

