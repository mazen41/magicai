foreach ($enTranslations as $key => $value) {
    if (is_string($value) && !empty($value)) {
        $translated = translateToArabic($value, $arabicTranslations);
        $arabicJson[$key] = $translated;
        
        if ($translated !== $value) {
            $translatedCount++;
        } else {
            $untranslatedCount++;
        }
    } else {
        $arabicJson[$key] = $value;
    }
}

// Write to resources/lang/ar.json
file_put_contents($arJsonPath, json_encode($arabicJson, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));

// Create lang/ar directory if it doesn't exist
if (!is_dir($langArDir)) {
    mkdir($langArDir, 0755, true);
}

// Write to lang/ar.json
file_put_contents($langArJsonPath, json_encode($arabicJson, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));

