// Function to translate a string to Arabic (exact match only)
function translateToArabic($text, $dictionary) {
    // Check if exact match exists in dictionary
    if (isset($dictionary[$text])) {
        return $dictionary[$text];
    }
    
    // If no exact match found, return original
    return $text;
}

